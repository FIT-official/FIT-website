import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import GameShell from '../components/sims/GameShell'
import { activities } from '../public/simulations/catalog'
import { emptyProgress, GAME_CHALLENGES, progressKey, recordAnswer } from '../lib/sims/game'

const sound = vi.hoisted(() => ({ play: vi.fn().mockResolvedValue(true), close: vi.fn(), create: vi.fn() }))
vi.mock('../lib/sims/sound', () => ({ createSoundPlayer: (...args) => { sound.create(...args); return sound } }))
vi.mock('next/dynamic', () => ({ default: loader => loader.toString().includes('GameShellStage')
  ? function Stage({ activity }) { return <div data-testid="lazy-experiment">{activity.id} experiment</div> }
  : function Canvas({ reducedMotion }) { return <div data-testid="lazy-art" data-reduced-motion={String(reducedMotion)} /> } }))

let visibility
beforeEach(() => {
  window.localStorage.clear()
  vi.clearAllMocks()
  vi.stubGlobal('IntersectionObserver', class { constructor(callback) { visibility = callback } observe() {} disconnect() {} })
  vi.stubGlobal('matchMedia', vi.fn(() => ({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn() })))
})
afterEach(() => { cleanup(); vi.restoreAllMocks(); vi.unstubAllGlobals(); vi.useRealTimers() })

describe('Game shell', () => {
  it('uses the same lazy shell for games while their players own the challenge score', () => {
    render(<GameShell activity={activities.find(activity => activity.id === 'ratio-sweets-share')} />)
    expect(screen.getByText('Try. Solve. Level up.')).toBeVisible()
    expect(screen.queryByLabelText('Concept checkpoint progress')).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: /Sound/ })).not.toBeInTheDocument()
    expect(screen.queryByTestId('lazy-experiment')).not.toBeInTheDocument()
    act(() => visibility([{ isIntersecting: true }]))
    expect(screen.getByTestId('lazy-experiment')).toHaveTextContent('ratio-sweets-share')
    expect(screen.getByRole('button', { name: /Start timer/ })).toBeVisible()
  })
  it('defers experiment and canvas until visible, then preserves the experiment on scroll-away', () => {
    render(<GameShell activity={activities[0]} />)
    expect(screen.queryByTestId('lazy-experiment')).not.toBeInTheDocument()
    expect(screen.queryByTestId('lazy-art')).not.toBeInTheDocument()
    act(() => visibility([{ isIntersecting: true }]))
    expect(screen.getByTestId('lazy-experiment')).toBeInTheDocument()
    expect(screen.getByTestId('lazy-art')).toHaveAttribute('data-reduced-motion', 'true')
    act(() => visibility([{ isIntersecting: false }]))
    expect(screen.queryByTestId('lazy-art')).not.toBeInTheDocument()
    expect(screen.getByTestId('lazy-experiment')).toBeInTheDocument()
  })
  it('starts muted, requires an explicit sound toggle and cleans up its own audio context', () => {
    const view = render(<GameShell activity={activities[0]} />)
    expect(screen.getByRole('button', { name: /Sound off/ })).toHaveAttribute('aria-pressed', 'false')
    expect(sound.create).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: /Sound off/ }))
    expect(sound.create).toHaveBeenCalledOnce()
    expect(screen.getByRole('button', { name: /Sound on/ })).toHaveAttribute('aria-pressed', 'true')
    view.unmount()
    expect(sound.close).toHaveBeenCalledOnce()
  })
  it('offers labelled radio choices, feedback and locally saved scoring', () => {
    render(<GameShell activity={activities[0]} />)
    expect(screen.getByRole('button', { name: /Check answer/ })).toBeDisabled()
    fireEvent.click(screen.getByRole('radio', { name: '3 Hz, with a suitable phase' }))
    fireEvent.click(screen.getByRole('button', { name: /Check answer/ }))
    expect(screen.getByRole('status')).toHaveTextContent('The signed folded frequency')
    expect(screen.getByLabelText('1 of 3 stars')).toBeVisible()
    expect(screen.getByText(/sampling rate clears the Nyquist limit/)).toBeVisible()
    expect(screen.getByRole('heading', { name: 'Explain · 2 of 3' })).toHaveFocus()
    expect(JSON.parse(window.localStorage.getItem(progressKey('sampling'))).challenges.alias.points).toBe(100)
    expect(sound.create).not.toHaveBeenCalled()
    expect(screen.getByText(/they do not measure your experiment/)).toBeVisible()
  })
  it('restores checkpoints after a new visit', () => {
    const saved = recordAnswer(emptyProgress(), GAME_CHALLENGES.sampling, 'alias', 0)
    window.localStorage.setItem(progressKey('sampling'), JSON.stringify(saved))
    render(<GameShell activity={activities[0]} />)
    expect(screen.getByLabelText('1 of 3 stars')).toBeVisible()
    expect(screen.getByRole('heading', { name: 'Explain · 2 of 3' })).toBeVisible()
  })
  it('keeps retries on the current level and shows storage failures without losing in-memory progress', () => {
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
    render(<GameShell activity={activities[0]} />)
    fireEvent.click(screen.getByRole('radio', { name: '5 Hz, at every phase' }))
    fireEvent.click(screen.getByRole('button', { name: /Check answer/ }))
    expect(screen.getByRole('heading', { name: 'Notice · 1 of 3' })).toBeVisible()
    expect(screen.getByRole('status')).toHaveTextContent('Keep exploring')
    expect(screen.getByText(/Browser storage is unavailable/)).toBeVisible()
    fireEvent.click(screen.getByRole('radio', { name: '3 Hz, with a suitable phase' }))
    fireEvent.click(screen.getByRole('button', { name: /Check answer/ }))
    expect(screen.getByLabelText('1 of 3 stars')).toBeVisible()
    expect(screen.getByText('75')).toBeVisible()
    vi.restoreAllMocks()
  })
  it('reports disabled browser storage before the first answer', () => {
    vi.spyOn(Storage.prototype, 'getItem').mockImplementation(() => { throw new Error('denied') })
    render(<GameShell activity={activities[0]} />)
    expect(screen.getByText(/Browser storage is unavailable/)).toBeVisible()
    expect(screen.getByLabelText('0 of 3 stars')).toBeVisible()
  })
  it('runs an opt-in timer only while the activity is visible', () => {
    vi.useFakeTimers()
    render(<GameShell activity={activities[0]} />)
    act(() => visibility([{ isIntersecting: true }]))
    act(() => vi.advanceTimersByTime(2000))
    expect(screen.getByText('00:00')).toBeVisible()
    fireEvent.click(screen.getByRole('button', { name: /Start timer/ }))
    act(() => vi.advanceTimersByTime(3000))
    expect(screen.getByText('00:03')).toBeVisible()
    act(() => visibility([{ isIntersecting: false }]))
    act(() => vi.advanceTimersByTime(3000))
    expect(screen.getByText('00:03')).toBeVisible()
    expect(window.localStorage.length).toBe(0)
  })
  it('pauses the optional timer when the browser tab is hidden', () => {
    vi.useFakeTimers()
    const visibilityState = vi.spyOn(document, 'visibilityState', 'get').mockReturnValue('visible')
    render(<GameShell activity={activities[0]} />)
    act(() => visibility([{ isIntersecting: true }]))
    fireEvent.click(screen.getByRole('button', { name: /Start timer/ }))
    act(() => vi.advanceTimersByTime(2000))
    expect(screen.getByText('00:02')).toBeVisible()
    visibilityState.mockReturnValue('hidden')
    fireEvent(document, new Event('visibilitychange'))
    act(() => vi.advanceTimersByTime(5000))
    expect(screen.getByText('00:02')).toBeVisible()
    visibilityState.mockReturnValue('visible')
    fireEvent(document, new Event('visibilitychange'))
    act(() => vi.advanceTimersByTime(1000))
    expect(screen.getByText('00:03')).toBeVisible()
  })
})
